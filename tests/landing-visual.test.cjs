'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const http=require('node:http');
const {chromium}=require('playwright');
const root=path.resolve(__dirname,'..');

test('Certus sales landing serves its real app screenshots and fits desktop/mobile',async()=>{
 const server=http.createServer((req,res)=>{const pathname=new URL(req.url,'http://local').pathname;const file=path.resolve(root,pathname==='/'?'index.html':`.${pathname}`);if(!file.startsWith(root)){res.writeHead(403).end();return}fs.readFile(file,(e,b)=>{if(e){res.writeHead(404).end();return}const ext=path.extname(file),type={'.html':'text/html; charset=utf-8','.css':'text/css','.png':'image/png','.jpg':'image/jpeg'}[ext]||'application/octet-stream';res.writeHead(200,{'content-type':type});res.end(b)})});
 await new Promise(r=>server.listen(0,'127.0.0.1',r));const browser=await chromium.launch({headless:true});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(`http://127.0.0.1:${server.address().port}/`,{waitUntil:'networkidle'});
  const promo=page.locator('#blackfriday-promo');
  await promo.waitFor({state:'visible'});
  assert.equal(await promo.evaluate(d=>d.open),true,'promotion modal should open on first visit');
  assert.match(await promo.innerText(),/Black Friday Certus/);
  assert.match(await promo.innerText(),/Black2026/);
  assert.match(await promo.innerText(),/25% de desconto/);
  assert.equal(await promo.locator('img').evaluate(i=>i.complete&&i.naturalWidth===1024),true,'promotion artwork should load');
  const promoLink=await promo.getByRole('link',{name:/Quero aproveitar a promoção/}).getAttribute('href');
  assert.match(promoLink,/wa\.me\/5516997902168/,'promotion CTA should open the confirmed commercial WhatsApp');
  await promo.getByRole('button',{name:'Fechar promoção'}).click();
  assert.equal(await promo.evaluate(d=>d.open),false,'X should close the promotion');
  assert.equal(await page.evaluate(()=>sessionStorage.getItem('certus-black-friday-promo-dismissed-2026')),'1','dismissal should persist for this browser session');
  await page.reload({waitUntil:'networkidle'});
  assert.equal(await promo.evaluate(d=>d.open),false,'a dismissed promotion should not reopen on refresh in the same session');
  await page.getByRole('heading',{name:/Controle de jornada/}).waitFor();
  const desktop=await page.evaluate(()=>({width:document.documentElement.scrollWidth,client:document.documentElement.clientWidth,imgs:[...document.images].map(i=>({src:i.getAttribute('src'),loaded:i.complete&&i.naturalWidth>0}))}));
  assert.ok(desktop.width<=desktop.client+1,'desktop page must not overflow horizontally');
  assert.ok(desktop.imgs.every(i=>i.loaded),`all landing images should load: ${JSON.stringify(desktop.imgs)}`);
  assert.deepEqual(errors,[]);
  await page.screenshot({path:'landing-preview/desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});await page.screenshot({path:'landing-preview/mobile.png',fullPage:true});
  const mobilePromo=await page.locator('#blackfriday-promo').evaluate(d=>{const r=d.getBoundingClientRect();return {open:d.open,width:r.width,client:document.documentElement.clientWidth,scrollWidth:document.documentElement.scrollWidth}});
  assert.equal(mobilePromo.open,false);
  assert.ok(mobilePromo.width<=mobilePromo.client,'promotion dialog fits mobile viewport');
  const mobile=await page.evaluate(()=>({width:document.documentElement.scrollWidth,client:document.documentElement.clientWidth}));
  assert.ok(mobile.width<=mobile.client+1,'mobile page must not expand viewport');
  assert.equal(await page.locator('.desktop-frame img').count(),1);
  assert.equal(await page.locator('.phone-frame img').count(),1);
  assert.equal(await page.locator('.tablet-frame img').count(),1);
  assert.equal(await page.locator('.desktop-frame img').count(),1);
  const deviceRatios=await page.evaluate(()=>['.desktop-frame img','.tablet-frame img','.phone-frame img'].map(s=>{const i=document.querySelector(s),r=i.getBoundingClientRect();return {selector:s,actual:r.width/r.height,native:i.naturalWidth/i.naturalHeight}}));
  assert.ok(deviceRatios.every(x=>Math.abs(x.actual-x.native)<0.04),`device screenshots must preserve their original proportions: ${JSON.stringify(deviceRatios)}`);
  const portraitTablet=await page.locator('.tablet-frame img').evaluate(i=>i.naturalHeight>i.naturalWidth);
  assert.equal(portraitTablet,true,'shared terminal must be shown on a portrait tablet');
  const deviceSizeRatio=await page.evaluate(()=>document.querySelector('.tablet-frame').getBoundingClientRect().width/document.querySelector('.phone-frame').getBoundingClientRect().width);
  assert.ok(deviceSizeRatio>1.4,`portrait tablet must be visibly larger than phone, width ratio=${deviceSizeRatio}`);
  const deviceOrder=await page.evaluate(()=>{const d=document.querySelector('.desktop-frame').getBoundingClientRect(),t=document.querySelector('.tablet-frame').getBoundingClientRect(),p=document.querySelector('.phone-frame').getBoundingClientRect();return {monitorOverlap:d.right-p.left,tabletToMonitor:t.left-d.left,phoneZ:getComputedStyle(document.querySelector('.phone-frame')).zIndex,tabletZ:getComputedStyle(document.querySelector('.tablet-frame')).zIndex}});
  assert.ok(deviceOrder.monitorOverlap>0&&deviceOrder.tabletToMonitor>0&&Number(deviceOrder.phoneZ)>Number(deviceOrder.tabletZ),`tablet sits at the right and the phone overlaps the monitor in the foreground: ${JSON.stringify(deviceOrder)}`);
  const standAlignment=await page.evaluate(()=>{const m=document.querySelector('.desktop-frame').getBoundingClientRect(),s=document.querySelector('.desktop-stand').getBoundingClientRect();return Math.abs((m.left+m.width/2)-(s.left+s.width/2))});
  assert.ok(standAlignment<2,`monitor stand must be centered under display, offset=${standAlignment}px`);
  const bezel=await page.locator('.desktop-frame').evaluate(e=>parseFloat(getComputedStyle(e).borderLeftWidth));
  assert.ok(bezel<=2.5,`monitor bezel should be slim, got ${bezel}px`);
  const tourTabs=page.locator('.tour-tab');
  assert.equal(await tourTabs.count(),17,'visual tour should cover all current company-management sections, employee portal and shared terminal');
  for(let i=0;i<await tourTabs.count();i++){
   const tab=tourTabs.nth(i),src=await tab.getAttribute('data-tour-src'),label=await tab.getAttribute('data-tour-title');
   await tab.click();
   await page.waitForFunction(src=>document.querySelector('#tour-image')?.getAttribute('src')===src,src,{timeout:10000});
   await page.locator('#tour-image').evaluate(img=>img.decode());
   assert.equal((await page.locator('#tour-title').innerText()).trim(),label,`tour screen ${label} should be selectable`);
   assert.ok(await page.locator('#tour-image').evaluate(img=>img.naturalWidth>0),`screenshot ${src} should load`);
  }
  await page.locator('.tour-tab').first().click();
  await page.locator('#tour-expand').click();
  await page.locator('#tour-dialog[open]').waitFor();
  await page.locator('#tour-dialog-close').click();
  await assert.deepEqual(errors,[]);
  assert.ok(await page.getByRole('link',{name:/Solicitar demonstração/}).count()>=1);
 }finally{await browser.close();await new Promise(r=>server.close(r))}
});
