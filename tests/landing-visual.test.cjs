'use strict';
const {test}=require('node:test');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const http=require('node:http');
const {chromium}=require('playwright');
const root=path.resolve(__dirname,'..');

test('Certus landing uses the approved palette and renders on desktop and mobile',async()=>{
 const server=http.createServer((req,res)=>{const pathname=new URL(req.url,'http://local').pathname;const file=path.resolve(root,pathname==='/'?'index.html':`.${pathname}`);if(!file.startsWith(root)){res.writeHead(403).end();return}fs.readFile(file,(e,b)=>{if(e){res.writeHead(404).end();return}const ext=path.extname(file),type={'.html':'text/html; charset=utf-8','.css':'text/css','.png':'image/png','.jpg':'image/jpeg'}[ext]||'application/octet-stream';res.writeHead(200,{'content-type':type});res.end(b)})});
 await new Promise(r=>server.listen(0,'127.0.0.1',r));const browser=await chromium.launch({headless:true});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(`http://127.0.0.1:${server.address().port}/`,{waitUntil:'networkidle'});
  await page.getByRole('heading',{name:/Controle de jornada/}).waitFor();
  assert.equal(await page.locator('#blackfriday-promo').count(),0,'the removed promotion modal must stay absent');
  const heroPrimary=page.locator('.hero-actions .btn-primary');
  assert.match(await heroPrimary.innerText(),/Conheça o Certus/);
  assert.equal(await heroPrimary.getAttribute('href'),'#demonstracao','Conheça o Certus should take visitors to Explore the Certus');
  const heroSecondary=page.locator('.hero-actions .btn-outline');
  assert.equal((await heroSecondary.innerText()).trim(),'Já sou cliente');
  assert.equal(await heroSecondary.getAttribute('href'),'https://vagasio.com.br/certus/','Já sou cliente should open the real login page');
  const headerDemo=page.locator('.header-actions .btn-primary');
  assert.match((await headerDemo.innerText()).trim(),/Solicitar demonstração/);
  assert.match(await headerDemo.getAttribute('href'),/^https:\/\/wa\.me\/5516997902168\?/,'Solicitar demonstração should open the confirmed commercial WhatsApp');
  const heroText=(await page.locator('.hero').innerText()).replace(/\s+/g,' ');
  assert.doesNotMatch(heroText,/off-line|gratuitos|59,90/i,'commercial proof points should not be stacked in the hero');
  const offline=page.locator('#solucoes .offline-note');
  assert.equal(await offline.count(),1,'offline message should be placed with product capabilities');
  const offlineWidth=await offline.evaluate(e=>e.getBoundingClientRect().width),sectionWidth=await page.locator('#solucoes .section-grid').evaluate(e=>e.getBoundingClientRect().width);
  assert.ok(offlineWidth>=sectionWidth*.9,`offline note should use the full feature section width (${offlineWidth}/${sectionWidth})`);
  assert.match((await offline.innerText()).replace(/\s+/g,' '),/funciona off-line em todo o sistema/i);
  assert.match((await offline.innerText()).replace(/\s+/g,' '),/sincronização prevista para cada fluxo e perfil/i);
  const pricing=(await page.locator('#planos').innerText()).replace(/\s+/g,' ');
  assert.match(pricing,/R\$ 59,90\s*\/mês/i,'starting price belongs in the plans section');
  assert.match(pricing,/Demonstração e teste gratuitos/i,'free demo and test belong with the commercial plans CTA');
  assert.equal(await page.locator('#planos .plan-highlights .plan-fact').count(),2,'present price and free trial as two separate visual items');
  assert.equal(await page.locator('.hero').count(),1);
  const palette=await page.evaluate(()=>{
   const css=s=>getComputedStyle(document.querySelector(s));
   return {theme:document.querySelector('meta[name="theme-color"]').content,bodyText:css('body').color,bodyBg:css('body').backgroundColor,shell:css('.dark-shell').backgroundColor,primary:css('.btn-primary').backgroundColor,featureBg:css('.feature-icon').backgroundColor,featureText:css('.feature-icon').color,eyebrow:css('.section-copy .eyebrow').color};
  });
  assert.equal(palette.theme,'#191316');
  assert.equal(palette.bodyText,'rgb(25, 19, 22)','body text should use black');
  assert.equal(palette.bodyBg,'rgb(255, 255, 255)','main background should use white');
  assert.equal(palette.primary,'rgb(123, 6, 54)','primary action should use wine');
  assert.equal(palette.featureBg,'rgb(246, 245, 246)','feature icon backing should use ice');
  assert.equal(palette.featureText,'rgb(123, 6, 54)','feature icons should use wine');
  assert.equal(palette.eyebrow,'rgb(123, 6, 54)','light-section accents should use wine');
  assert.equal(await page.locator('#back-to-top').getAttribute('href'),'#inicio','floating button should return to the page start');
  const backgroundMotion=await page.evaluate(()=>({hero:getComputedStyle(document.querySelector('.dark-shell')).animationName,heroBand:getComputedStyle(document.querySelector('.dark-shell'),'::before').animationName,heroLine:getComputedStyle(document.querySelector('.dark-shell'),'::after').animationName,plans:getComputedStyle(document.querySelector('#planos')).animationName,plansRing:getComputedStyle(document.querySelector('#planos'),'::after').animationName}));
  assert.equal(backgroundMotion.hero,'aurora-drift','hero background gently moves like an aurora');
  assert.equal(backgroundMotion.heroBand,'aurora-ring','large existing contour ring gently drifts');
  assert.equal(backgroundMotion.heroLine,'aurora-ring-fine','fine contour ring has independent motion');
  assert.equal(backgroundMotion.plans,'cta-color-flow','plans section uses a slow flowing gradient');
  assert.equal(backgroundMotion.plansRing,'cta-ring-drift','plans contour moves subtly');
  const wineMotionColors=await page.evaluate(()=>({hero:getComputedStyle(document.querySelector('#inicio')).backgroundImage,heroBand:getComputedStyle(document.querySelector('#inicio'),'::before').borderTopColor,plans:getComputedStyle(document.querySelector('#planos')).backgroundImage}));
  assert.match(wineMotionColors.hero,/rgba\(168, 13, 76, 0\.8\)/,'hero aurora should have a clearly visible brand-wine glow');
  assert.match(wineMotionColors.hero,/rgba\(123, 6, 54, 0\.73\)/,'deep wine should be a dominant part of the moving hero backdrop');
  assert.match(wineMotionColors.heroBand,/rgba\(199, 123, 156, 0\.4\)/,'large contour should pick up a subtle wine tint');
  assert.match(wineMotionColors.plans,/rgb\(123, 6, 54\)/,'plans backdrop should use the brand wine');
  assert.doesNotMatch(wineMotionColors.hero,/rgba\(155, 80, 201/,'remove the mistaken violet hue from the aurora');
  const initialAuroraPosition=await page.locator('#inicio').evaluate(e=>getComputedStyle(e).backgroundPosition);
  await page.waitForTimeout(900);
  const nextAuroraPosition=await page.locator('#inicio').evaluate(e=>getComputedStyle(e).backgroundPosition);
  assert.notEqual(nextAuroraPosition,initialAuroraPosition,'the aurora background position changes over time');
  assert.equal(await page.locator('#back-to-top').getAttribute('aria-hidden'),'true','back-to-top is hidden until the visitor scrolls');
  assert.ok(await page.locator('.feature-card[data-reveal]').count()>=6,'feature cards should be progressively revealed on scroll');
  assert.ok(await page.locator('.feature-card').first().evaluate(e=>getComputedStyle(e).transitionDuration.split(',')[0].trim()!=='0s'),'interactive cards should have a subtle transition');
  await page.evaluate(()=>window.scrollTo({top:650,behavior:'instant'}));
  await page.waitForFunction(()=>document.querySelector('#back-to-top')?.getAttribute('aria-hidden')==='false');
  await page.locator('#back-to-top').click();
  await page.waitForFunction(()=>window.scrollY<5,{timeout:6000});
  await page.waitForFunction(()=>document.querySelector('#back-to-top')?.getAttribute('aria-hidden')==='true');
  const desktop=await page.evaluate(()=>({width:document.documentElement.scrollWidth,client:document.documentElement.clientWidth,imgs:[...document.images].map(i=>({src:i.getAttribute('src'),loaded:i.complete&&i.naturalWidth>0}))}));
  assert.ok(desktop.width<=desktop.client+1,'desktop page must not overflow horizontally');
  const revealTargets=await page.locator('[data-reveal]').count();
  for(let i=0;i<revealTargets;i++){
   await page.locator('[data-reveal]').nth(i).evaluate(el=>el.scrollIntoView({block:'center',behavior:'instant'}));
   await page.waitForTimeout(45);
  }
  assert.equal(await page.locator('[data-reveal]:not(.is-visible)').count(),0,'every section and card becomes visible as it enters the viewport');
  await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
  await page.waitForTimeout(650);
  assert.ok(desktop.imgs.every(i=>i.loaded),`all landing images should load: ${JSON.stringify(desktop.imgs)}`);
  assert.deepEqual(errors,[]);
  await page.screenshot({path:'landing-preview/desktop.png',fullPage:true});
  await page.setViewportSize({width:390,height:844});
  const mobile=await page.evaluate(()=>({width:document.documentElement.scrollWidth,client:document.documentElement.clientWidth}));
  assert.ok(mobile.width<=mobile.client+1,'mobile page must not expand viewport');
  const planFactRects=await page.locator('#planos .plan-fact').evaluateAll(es=>es.map(e=>{const r=e.getBoundingClientRect();return {top:r.top,bottom:r.bottom,width:r.width}}));
  assert.equal(planFactRects.length,2);
  assert.ok(planFactRects[1].top>=planFactRects[0].bottom-1,'price and free-trial tiles should stack clearly on mobile');
  assert.equal(await page.locator('.desktop-frame img').count(),1);
  assert.equal(await page.locator('.phone-frame img').count(),1);
  assert.equal(await page.locator('.tablet-frame img').count(),1);
  const deviceRatios=await page.evaluate(()=>['.desktop-frame img','.tablet-frame img','.phone-frame img'].map(s=>{const i=document.querySelector(s),r=i.getBoundingClientRect();return {selector:s,actual:r.width/r.height,native:i.naturalWidth/i.naturalHeight}}));
  assert.ok(deviceRatios.every(x=>Math.abs(x.actual-x.native)<0.04),`device screenshots must preserve original proportions: ${JSON.stringify(deviceRatios)}`);
  const deviceSizeRatio=await page.evaluate(()=>document.querySelector('.tablet-frame').getBoundingClientRect().width/document.querySelector('.phone-frame').getBoundingClientRect().width);
  assert.ok(deviceSizeRatio>1.4,`portrait tablet must be visibly larger than phone, width ratio=${deviceSizeRatio}`);
  await page.screenshot({path:'landing-preview/mobile.png',fullPage:true});
  const tourTabs=page.locator('.tour-tab');
  assert.equal(await tourTabs.count(),17,'visual tour should cover company, employee and shared-terminal screens');
  for(let i=0;i<await tourTabs.count();i++){
   const tab=tourTabs.nth(i),src=await tab.getAttribute('data-tour-src'),label=await tab.getAttribute('data-tour-title');
   await tab.click();
   await page.waitForFunction(src=>document.querySelector('#tour-image')?.getAttribute('src')===src,src,{timeout:10000});
   await page.locator('#tour-image').evaluate(img=>img.decode());
   assert.equal((await page.locator('#tour-title').innerText()).trim(),label,`tour screen ${label} should be selectable`);
   assert.ok(await page.locator('#tour-image').evaluate(img=>img.naturalWidth>0),`screenshot ${src} should load`);
  }
  await page.locator('.tour-tab').first().click();
  await page.locator('#tour-expand').click();
  await page.locator('#tour-dialog[open]').waitFor();
  await page.locator('#tour-dialog-close').click();
  assert.deepEqual(errors,[]);
  assert.ok(await page.getByRole('link',{name:/Solicitar demonstração/}).count()>=1);
  const reducedPage=await browser.newPage({viewport:{width:390,height:844}});
  await reducedPage.emulateMedia({reducedMotion:'reduce'});
  await reducedPage.goto(`http://127.0.0.1:${server.address().port}/`,{waitUntil:'networkidle'});
  assert.equal(await reducedPage.locator('html').evaluate(e=>e.classList.contains('motion-ready')),false,'scroll-reveal motion is disabled when reduced motion is requested');
  const reducedMotionNames=await reducedPage.evaluate(()=>({hero:getComputedStyle(document.querySelector('.dark-shell')).animationName,heroBand:getComputedStyle(document.querySelector('.dark-shell'),'::before').animationName,plans:getComputedStyle(document.querySelector('#planos')).animationName}));
  assert.deepEqual(reducedMotionNames,{hero:'none',heroBand:'none',plans:'none'},'moving backgrounds must stop for reduced-motion preference');
  assert.equal(await reducedPage.locator('.feature-card').first().evaluate(e=>getComputedStyle(e).opacity),'1','all content remains visible without reveal animation');
  await reducedPage.evaluate(()=>window.scrollTo({top:700,behavior:'instant'}));
  await reducedPage.waitForFunction(()=>document.querySelector('#back-to-top')?.getAttribute('aria-hidden')==='false');
  await reducedPage.locator('#back-to-top').click();
  await reducedPage.waitForFunction(()=>window.scrollY<5,{timeout:1500});
  await reducedPage.close();
  assert.deepEqual(errors,[]);
 }finally{await browser.close();await new Promise(r=>server.close(r))}
});
